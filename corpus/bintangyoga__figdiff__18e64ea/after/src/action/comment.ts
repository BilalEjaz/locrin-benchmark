import type { Summary } from "../diff/types.js";
import { formatSummary } from "../report.js";
import type { ChangedFile } from "./changed-files.js";

/** Hidden marker used to find our own comment again on later pushes. */
export const COMMENT_MARKER = "<!-- figdiff-comment -->";

/** GitHub rejects comments over 65,536 characters; stay well below. */
const MAX_COMMENT = 60_000;
const MAX_FILE_TEXT = 15_000;

export interface FileResult {
  file: ChangedFile;
  /** Present when the two versions were compared. */
  summary?: Summary;
  /** The text diff, as printed by `figdiff`. */
  text?: string;
  /** Why the comparison could not be made. */
  error?: string;
  /** Name of the HTML report written for this file, if any. */
  reportName?: string;
}

export interface CommentContext {
  /** Link to the workflow run, where the report artifact can be downloaded. */
  runUrl?: string;
  /** Whether the HTML reports were uploaded as an artifact. */
  reportsUploaded: boolean;
  version?: string;
}

/** A file counts as changed unless it was only re-saved without any design difference. */
export function isSubstantive(r: FileResult): boolean {
  if (r.error) return true;
  if (r.file.status === "added" || r.file.status === "deleted" || r.file.status === "renamed") return true;
  return (r.summary?.changes ?? 0) > 0;
}

/** Wrap text in a code span, choosing a delimiter that cannot be broken by backticks inside. */
function code(text: string): string {
  const longest = Math.max(0, ...(text.match(/`+/g) ?? []).map((m) => m.length));
  const fence = "`".repeat(longest + 1);
  return `${fence}${text.startsWith("`") || text.endsWith("`") ? ` ${text} ` : text}${fence}`;
}

/** A fenced code block whose fence is longer than any backtick run inside. */
function block(text: string): string {
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((m) => m.length));
  const fence = "`".repeat(longest + 1);
  return `${fence}text\n${text.replace(/\n$/, "")}\n${fence}`;
}

function truncate(text: string, limit: number): string {
  if (text.length <= limit) return text;
  const cut = text.slice(0, limit);
  const kept = cut.slice(0, Math.max(cut.lastIndexOf("\n"), 0));
  const hidden = text.slice(kept.length).split("\n").filter(Boolean).length;
  return `${kept}\n… ${hidden} more lines not shown`;
}

function section(r: FileResult): string {
  const { file } = r;
  const name = code(file.path);
  switch (file.status) {
    case "added":
      return `**${name}**: new design file, nothing earlier to compare with.`;
    case "deleted":
      return `**${name}**: design file deleted.`;
    default:
  }
  const renamed = file.status === "renamed" ? ` (renamed from ${code(file.oldPath ?? "")})` : "";
  if (r.error) return `**${name}**${renamed}: could not be compared. ${r.error}`;
  if (!r.summary || r.summary.changes === 0) {
    return `**${name}**${renamed}: ${file.status === "renamed" ? "renamed, no design changes." : "saved again, no design changes."}`;
  }
  const details = r.text
    ? `\n\n<details><summary>Show changes</summary>\n\n${block(truncate(r.text, MAX_FILE_TEXT))}\n\n</details>`
    : "";
  return `**${name}**${renamed}: ${formatSummary(r.summary)}${details}`;
}

/** The pull request comment for a set of compared files. */
export function buildComment(results: FileResult[], ctx: CommentContext): string {
  const parts = [`${COMMENT_MARKER}\n## Design changes`, ...results.map(section)];
  if (ctx.reportsUploaded && ctx.runUrl && results.some((r) => r.reportName)) {
    parts.push(`Full HTML reports (with filters and, if enabled, images) are attached to [this workflow run](${ctx.runUrl}) as the artifact **figdiff-reports**.`);
  }
  parts.push(`<sub>Generated by figdiff${ctx.version ? ` ${ctx.version}` : ""}. Changes are matched by node id.</sub>`);
  const body = parts.join("\n\n");
  return body.length <= MAX_COMMENT ? body : `${body.slice(0, MAX_COMMENT)}\n\n… (comment shortened)`;
}

/** Replaces an earlier comment when a later push no longer changes any design file. */
export function buildEmptyComment(): string {
  return `${COMMENT_MARKER}\n## Design changes\n\nThis pull request no longer changes any design file.`;
}
